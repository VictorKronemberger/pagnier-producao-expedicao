import {mergeShipment} from "../lib/shipment-groups.mjs";
import assert from "node:assert/strict";
import {emptyShipment,newBox,newItem,normalizeShipment,canonicalShipping} from "../lib/shipping.mjs";
import {selectAssemblyMode} from "../lib/assembly-mode.mjs";
import {startSmallBox,finishSmallBox,duplicateSmallBox,placeSmallBox,unpackSmallBox} from "../lib/assembly-flow.mjs";
import {smallBoxOptions} from "../lib/small-box-search.mjs";
import {boxReviewKey} from "../lib/box-review.mjs";
import {deleteShippingBox} from "../lib/delete-shipping-box.mjs";
const ops=[{id:"stock-craft",nome:"Artesanato liberado",produto:"Artesanato de teste",quantidade:"20",unidade:"UNID",estoque:true}];
let s=startSmallBox(selectAssemblyMode(emptyShipment(),"bags"),"bag-a");
assert.equal(s.caixasEmMontagem[0].tipo,"bag");assert.equal(s.caixasEmMontagem[0].codigo,"BAG-01");
s.caixasEmMontagem[0].itens=[{...newItem("i-a"),opId:ops[0].id,produto:ops[0].produto,unidade:"UNID",quantidade:"4",caixaInternaId:"bag-a"}];
s=normalizeShipment(s,ops);assert.equal(s.caixasEmMontagem[0].tipo,"bag");
s=finishSmallBox(s,"bag-a",ops);let n=0;s=duplicateSmallBox(s,"bag-a",1,ops,()=> "copy-"+(++n));
assert.equal(s.caixasEmMontagem[1].tipo,"bag");assert.equal(smallBoxOptions(s.caixasEmMontagem,"bag").length,2);
assert.throws(()=>selectAssemblyMode(s,"inner"),/misto/);assert.throws(()=>selectAssemblyMode(s,"direct"));
s.caixas=[{...newBox([],"outer"),montada:false,pesoBrutoKg:"2"}];
s=placeSmallBox(s,"bag-a","outer",ops);s=normalizeShipment(s,ops);
assert.equal(s.caixas[0].caixasInternas[0].tipo,"bag");assert.equal(s.caixas[0].pesoBrutoKg,"");
assert.equal(s.caixas[0].itens[0].quantidade,"4");assert.equal(s.caixasEmMontagem.length,1);
s=unpackSmallBox(s,"outer","bag-a","unused");s=normalizeShipment(s,ops);
assert.equal(s.caixasEmMontagem.find(b=>b.id==="bag-a").tipo,"bag");assert.equal(s.caixas[0].itens.length,0);
assert.throws(()=>normalizeShipment({...s,caixasEmMontagem:s.caixasEmMontagem.map(b=>({...b,tipo:"invalid"}))},ops));
const key=boxReviewKey(s,ops),old=structuredClone(s);delete old.caixasEmMontagem[0].tipo;assert.notEqual(boxReviewKey(old,ops),key);
const mixed=selectAssemblyMode(s,"mixed"),both=startSmallBox(mixed,"box-a");
assert.equal(both.caixasEmMontagem.at(-1).tipo,undefined);assert.doesNotThrow(()=>normalizeShipment(both,ops));
const legacy=canonicalShipping({...emptyShipment(),caixasEmMontagem:[{id:"legacy",codigo:"INT-01",pronta:false,itens:[]}]});
assert.equal(Object.hasOwn(legacy.caixasEmMontagem[0],"tipo"),false);
const removed=deleteShippingBox(s,"small","bag-a","EXCLUIR");assert(!removed.caixasEmMontagem.some(b=>b.id==="bag-a"));
assert.throws(()=>duplicateSmallBox(s,"bag-a",5,ops),/excede|Saldo/);
console.log("OK bags: released resale, save/reload, copy, distribution, unpack, balance, delete, mixed, legacy and review invalidation.");

const other=startSmallBox(selectAssemblyMode(emptyShipment(),"inner"),"old-box");
const merged=mergeShipment({details:{A:{envio:s},B:{envio:other}}},"A",["A","B"],{key:"a".repeat(64),nome:"Cliente teste"},{},"2026-10-27T12:00:00.000Z",()=> "merge-"+(++n));
assert.equal(merged.organizacao,"mixed");assert.equal(merged.caixasEmMontagem.filter(b=>b.tipo==="bag").length,2);assert.doesNotThrow(()=>normalizeShipment(merged,ops));
const combined=mergeShipment({details:{A:{envio:emptyShipment()},B:{envio:s}}},"A",["A","B"],{key:"a".repeat(64),nome:"Cliente teste"},{},"2026-10-27T12:00:00.000Z",()=> "merge-"+(++n));assert.equal(combined.organizacao,"bags");assert.doesNotThrow(()=>normalizeShipment(combined,ops));
console.log("OK bags grouping: preserves bag types and enables mixed assembly when combining with boxes.");
