import assert from "node:assert/strict";
import {smallBoxOptions,smallBoxContents,smallBoxQuantity} from "../lib/small-box-search.mjs";
import {emptyShipment,newBox,newItem} from "../lib/shipping.mjs";
import {placeSmallBox} from "../lib/assembly-flow.mjs";

const op={id:"op",nome:"OP teste",produto:"Rapé teste 50g",unidade:"UNID",quantidade:"100"};
const makeBox=(id,quantity,pronta=true)=>({id,codigo:"Caixa repetida",pronta,itens:[{...newItem("item-"+id),opId:op.id,produto:op.produto,unidade:op.unidade,quantidade:quantity,caixaInternaId:id}]});
const boxes=[makeBox("a","20"),makeBox("b","30"),makeBox("c","30"),makeBox("draft","10",false)];
const before=structuredClone(boxes);
const options=smallBoxOptions(boxes);
assert.equal(options.length,3);
assert.match(options[0].label,/20 UNID/);
assert.match(options[1].label,/30 UNID/);
assert.notEqual(options[1].label,options[2].label,"identical content remains distinguishable");
assert.deepEqual(smallBoxOptions(boxes,"  RAPE   50G  ").map(b=>b.id),["a","b","c"]);
assert.deepEqual(smallBoxOptions(boxes,"REPETIDA 20").map(b=>b.id),["a"]);
assert.equal(smallBoxOptions(boxes,"missing").length,0);
assert.equal(smallBoxOptions(boxes,"   ").length,3);
assert.deepEqual(smallBoxOptions(),[]);
assert.equal(smallBoxContents([{produto:"Pó",quantidade:"1,250",unidade:"KG"},{produto:"Frasco",quantidade:"2",unidade:"UNID"}]),"1,25 KG de Pó; 2 UNID de Frasco");
assert.equal(smallBoxContents([{produto:"Pó",quantidade:"0.125",unidade:"KG"}]),"0,125 KG de Pó");
assert.match(smallBoxContents([{produto:"Pó",quantidade:"inválida",unidade:"KG"}]),/Quantidade a revisar/);
assert.deepEqual(boxes,before,"search must never mutate shipment data");
const shipment={...emptyShipment(),caixas:[newBox([],"outer")],caixasEmMontagem:boxes};
const selected=smallBoxOptions(boxes,"30")[1];
const placed=placeSmallBox(shipment,selected.id,"outer",[op]);
assert.equal(placed.caixas[0].caixasInternas[0].id,"c");
assert.equal(placed.caixas[0].itens[0].quantidade,"30");
assert.deepEqual(smallBoxOptions(placed.caixasEmMontagem).map(b=>b.id),["a","b"]);
assert.throws(()=>placeSmallBox(placed,"c","outer",[op]));
assert.deepEqual(shipment.caixasEmMontagem,before);
console.log("OK: pesquisa por texto, acentos, quantidade, caixas iguais, unidades mistas, decimais, vazio e transferência pelo ID sem duplicar.");

assert.equal(options[0].title,"Caixa repetida");
assert.equal(options[0].quantity,"20 UNID");
assert.equal(options[0].number,1);
assert.equal(smallBoxQuantity([{quantidade:"0,1",unidade:"KG"},{quantidade:"0,2",unidade:"kg"}]),"0,3 KG");
assert.equal(smallBoxQuantity([{quantidade:"2",unidade:"UNID"},{quantidade:"1,25",unidade:"KG"}]),"2 UNID + 1,25 KG");
assert.equal(smallBoxQuantity([]),"Vazia");
assert.equal(smallBoxQuantity([{quantidade:"inválida",unidade:"KG"}]),"Revisar quantidade");
console.log("OK: resumos compactos, totais por unidade sem misturar medidas e precisão decimal.");
