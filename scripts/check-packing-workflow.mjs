import assert from "node:assert/strict";
import {fixture} from "./packing-fixture.mjs";
import {packingWorkflow} from "../lib/packing-workflow.mjs";
import {confirmBoxReview} from "../lib/box-review.mjs";
const {shipment,ops}=fixture();
assert.equal(packingWorkflow(undefined,ops).next,"orders");
assert.equal(packingWorkflow(shipment,ops).next,"boxes");
const ready=confirmBoxReview(shipment,ops,"Victor","2026-10-15T15:00:00Z");
assert.equal(packingWorkflow(ready,ops).next,"review");assert(packingWorkflow(ready,ops).ready);
assert(!packingWorkflow(ready,ops).states.review.done,"final review must never be inferred from complete data");
const edited=structuredClone(ready);edited.caixas[0].itens[0].hsCode="";
assert.equal(packingWorkflow(edited,ops).next,"boxes");assert(packingWorkflow(edited,ops).physical.reviewed,"document fields do not invalidate physical review");
const document=structuredClone(ready);document.packing.invoiceNumero="";
assert.equal(packingWorkflow(document,ops).next,"document");
const recipient=structuredClone(ready);recipient.packing.destinatarioEndereco="";assert.equal(packingWorkflow(recipient,ops).next,"orders");
const moved=structuredClone(ready);moved.caixas[0].pesoBrutoKg="12";assert.equal(packingWorkflow(moved,ops).next,"boxes");assert(!packingWorkflow(moved,ops).physical.reviewed);
const deleted={...ready,packingExcluido:true};assert(!packingWorkflow(deleted,ops).ready);
const original=JSON.stringify(ready);packingWorkflow(ready,ops);assert.equal(JSON.stringify(ready),original);
console.log("OK fluxo packing: retomada por pendência, destinatário, dados físicos/documentais, nova conferência após alteração, exclusão preservada e revisão final nunca presumida.");
