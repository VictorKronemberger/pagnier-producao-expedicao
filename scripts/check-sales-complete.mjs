import assert from "node:assert/strict";
import {initialSync,syncStep,publicSync} from "../lib/nomus-sync.mjs";
import {mergeSalesImport} from "../lib/sales-import.mjs";
let s=initialSync({grupos:[],semVinculo:[]});
s.ordersComplete=true;s.turn=4;s.orders={1:{createdDate:"2026-10-01",companyId:1,code:"HIST",clientId:9,active:false,items:[{productId:8,quantity:"2"}]}};
let url="";
s=await syncStep(s,"dummy",{fetcher:async u=>{url=u;return Response.json({nome:"Cliente histórico"})}});
assert(url.endsWith("/clientes/9"));assert.equal(s.clients[9],"Cliente histórico");
s=await syncStep({...s,turn:4,nextAt:0},"dummy",{fetcher:async u=>{url=u;return Response.json({descricao:"Produto histórico",siglaUnidadeMedida:"UN"})}});
assert(url.endsWith("/produtos/8"));assert.equal(publicSync(s,true).pedidosIdentificados,1);
const many=await syncStep({...s,turn:0,nextAt:0,pages:{...s.pages,orders:201}},"dummy",{fetcher:async()=>Response.json(Array.from({length:50},(_,i)=>({id:10000+i,idEmpresa:1,codigoPedido:"P"+i,idPessoaCliente:9,itensPedido:[]})))});
assert.equal(many.pages.orders,202);
const base=structuredClone(s),latest=structuredClone(s),incoming=structuredClone(s);
latest.snapshot.grupos=[{id:"ATIVO",codigo:"ATIVO",cliente:"Nome atual",ordens:[{id:"OPNOVA"}]}];
latest.orders[2]={companyId:1,code:"ATIVO",active:true,clientId:10,items:[],listHash:"concurrent"};
incoming.orders[3]={companyId:1,code:"NOVO",active:true,clientId:11,items:[]};incoming.clients[11]="Cliente novo";
const merged=mergeSalesImport(base,latest,incoming);
assert.equal(merged.snapshot.grupos.find(g=>g.id==="ATIVO").ordens[0].id,"OPNOVA");
assert(merged.orders[2]);assert(merged.orders[3]);assert(!merged.snapshot.grupos.some(g=>g.id==="HIST"));
assert.equal(merged.snapshot.grupos.find(g=>g.id==="NOVO").cliente,"Cliente novo");
console.log("OK: nomes de pedidos históricos, paginação acima de 200 e mesclagem preservando atualizações concorrentes e OPs.");
