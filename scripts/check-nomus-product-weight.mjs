import assert from "node:assert/strict";
import {netWeight,applyNomusWeights,needsNomusWeight} from "../lib/nomus-product-weight.mjs";
import {productDocumentData,documentProductId} from "../lib/packing-product-data.mjs";
import {emptyShipment,newBox,newItem,canonicalShipping,normalizeShipment} from "../lib/shipping.mjs";
const op={id:"stock-test",productId:71,nome:"Estoque",produto:"Fixture product",unidade:"UNID",quantidade:"30"};
const row=productDocumentData({descricao:op.produto,siglaUnidadeMedida:"UNID",pesoLiquidoUnitario:"0,2",pesoBrutoUnitario:"0,8"},op);
assert.equal(row.pesoLiquidoUnitarioKg,"0,200");assert.equal(documentProductId({},op),71);
for(const input of [null,undefined,"",0,"0,000","-1","NaN","1kg","0.0001"])assert.equal(netWeight(input),"");
assert.equal(netWeight(1.25),"1,250");
const item={...newItem("item-1"),opId:op.id,produto:op.produto,unidade:"UNID",quantidade:"5",unidadesEmbaladas:"5"};
const shipment={...emptyShipment(),caixas:[{...newBox([],"box-1"),montada:true,pesoBrutoKg:"2",itens:[item,{...item,id:"item-2",origemPeso:"produto",pesoUnitarioKg:"0,100"},{...item,id:"item-3",origemPeso:"manual",pesoUnitarioKg:"0,300"},{...item,id:"item-4",pesoUnitarioKg:"0,400"}]}],caixasEmMontagem:[{id:"inner-1",codigo:"INT-01",pronta:true,itens:[{...item,id:"item-5",caixaInternaId:"inner-1"}]}]};
const before=JSON.stringify(shipment),result=applyNomusWeights(shipment,[row]);
assert.equal(result.filled,3);assert.equal(JSON.stringify(shipment),before);
assert.equal(result.shipment.caixas[0].itens[0].pesoUnitarioKg,"0,200");
assert.equal(result.shipment.caixas[0].itens[0].quantidade,"5");
assert.equal(result.shipment.caixas[0].itens[0].unidadesEmbaladas,"5");
assert.equal(result.shipment.caixas[0].itens[2].pesoUnitarioKg,"0,300");
assert.equal(result.shipment.caixas[0].itens[3].pesoUnitarioKg,"0,400");
assert.equal(result.shipment.caixas[0].montada,false);assert.equal(result.shipment.caixas[0].pesoBrutoKg,"");
assert.equal(result.shipment.caixasEmMontagem[0].pronta,false);
assert.equal(canonicalShipping(result.shipment).caixas[0].itens[0].origemPeso,"nomus");
assert.doesNotThrow(()=>normalizeShipment(result.shipment,[op],shipment));
assert.equal(applyNomusWeights(result.shipment,[row]).shipment,result.shipment);
assert.equal(applyNomusWeights(shipment,[{...row,produto:"Other"}]).filled,0);
assert.equal(applyNomusWeights(shipment,[{...row,opId:"other-stock"}]).filled,0);
assert.equal(applyNomusWeights(shipment,[{...row,pesoLiquidoUnitarioKg:"0"}]).filled,0);
assert.equal(needsNomusWeight({...item,origemPeso:"manual",pesoUnitarioKg:""}),false);
assert.equal(needsNomusWeight({...item,unidade:"L"}),false);
const liquid={...item,unidade:"L",conteudoPorEmbalagem:"0,250"};
const liquidShipment={...emptyShipment(),caixas:[{...newBox([],"liquid"),itens:[liquid]}]};
assert.equal(applyNomusWeights(liquidShipment,[{...row,unidade:"L",pesoLiquidoUnitarioKg:"0,800"}]).shipment.caixas[0].itens[0].pesoUnitarioKg,"0,200");
console.log("OK Nomus net weight: exact product, stock items, repeated rows, decimal parsing, pack conversion, manual edits, quantities, review reset and persistence.");
