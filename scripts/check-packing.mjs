import assert from "node:assert/strict";
import {mkdirSync,writeFileSync} from "node:fs";
import {fixture} from "./packing-fixture.mjs";
import {inspectPacking,weightText} from "../lib/packing-list.mjs";
import {packingDefinition,packingBlob} from "../lib/packing-pdf.mjs";
import {normalizeShipment,newItem} from "../lib/shipping.mjs";
const {shipment,ops}=fixture();let report=inspectPacking(shipment,ops);
assert.deepEqual(report.issues,[]);assert.equal(report.totalUnits,2);assert.equal(report.totalNet,10000n);assert.equal(weightText(report.totalNet),"10,000");
assert.deepEqual(normalizeShipment(shipment,ops),shipment);
const mismatch=structuredClone(shipment);mismatch.caixas[0].itens[0].unidadesEmbaladas="3";
assert(inspectPacking(mismatch,ops).issues.some(i=>i.includes("não corresponde")));
assert.throws(()=>packingDefinition(mismatch,ops));assert(packingDefinition(mismatch,ops,{draft:true}).watermark);
const invalid=structuredClone(shipment);invalid.caixas[0].itens[0].unidadesEmbaladas="1.5";assert.throws(()=>normalizeShipment(invalid,ops));
invalid.caixas[0].itens[0].unidadesEmbaladas="2";invalid.packing.invoiceData="2026-02-30";assert.throws(()=>normalizeShipment(invalid,ops));
const liquid=structuredClone(shipment);const liquidOps=[{...ops[0],unidade:"L",quantidade:"1"}];
Object.assign(liquid.caixas[0],{pesoBrutoKg:"1,2",pesoLiquidoKg:"1,1"});
Object.assign(liquid.caixas[0].itens[0],{unidade:"L",quantidade:"1",pesoUnitarioKg:"0,550"});
assert(inspectPacking(liquid,liquidOps).issues.some(i=>i.includes("conteúdo por embalagem")));
liquid.caixas[0].itens[0].conteudoPorEmbalagem="0,5";assert.deepEqual(inspectPacking(liquid,liquidOps).issues,[]);
const exact=structuredClone(shipment),exactOps=[{...ops[0],quantidade:"3",unidade:"UN"}];
Object.assign(exact.caixas[0],{pesoLiquidoKg:"0,117",pesoBrutoKg:"0,2"});
Object.assign(exact.caixas[0].itens[0],{quantidade:"3",unidade:"UN",unidadesEmbaladas:"3",pesoUnitarioKg:"0,039"});
assert.equal(inspectPacking(exact,exactOps).totalNet,117n);assert.deepEqual(inspectPacking(exact,exactOps).issues,[]);
const incomplete=structuredClone(shipment);incomplete.packing.exportadorEndereco="";assert.throws(()=>packingDefinition(incomplete,ops));
mkdirSync(".sites-runtime",{recursive:true});
const blob=await packingBlob(shipment,ops,{draft:true});writeFileSync(".sites-runtime/packinglist-demonstracao.pdf",Buffer.from(await blob.arrayBuffer()));
const many=structuredClone(shipment);many.caixas[0].itens=Array.from({length:100},(_,i)=>({...newItem("i-"+i),...shipment.caixas[0].itens[0],id:"i-"+i,descricaoDocumento:"Product "+i+" — description for pagination testing. ".repeat(4),quantidade:"0,1",unidadesEmbaladas:"1",pesoUnitarioKg:"0,1"}));
assert.deepEqual(inspectPacking(many,ops).issues,[]);
const longBlob=await packingBlob(many,ops);writeFileSync(".sites-runtime/packinglist-paginacao.pdf",Buffer.from(await longBlob.arrayBuffer()));
console.log("OK: peso por unidade, unidades de embalagem, kg/UN/L, precisão em gramas, validação, rascunho e PDF com 100 linhas.");
