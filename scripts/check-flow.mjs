import assert from "node:assert/strict";
import {recipientPatch,pendingOrderSelection,bridgeDestination} from "../lib/packing-flow.mjs";
import {emptyShipment} from "../lib/shipping.mjs";
const doc={nome:"Cliente",razaoSocial:"Nome cadastral",registro:"Registro",telefone:"123",email:"cadastro@example.invalid",pais:"Brasil"};
const prior={destinatarioNome:"Nome revisado",destinatarioEndereco:"Endereço revisado",contatoEmail:"manual@example.invalid"};
assert.deepEqual(recipientPatch(prior,doc,"Endereço cadastral"),{destinatarioRegistro:"Registro",contatoTelefone:"123",paisDestino:"Brasil"});
assert.equal(recipientPatch(prior,doc,"",true).destinatarioEndereco,"");
assert.equal(recipientPatch(prior,doc,"Novo",true).contatoEmail,doc.email);
assert.equal(prior.destinatarioEndereco,"Endereço revisado");
assert.equal(pendingOrderSelection(["P2","P1"],["P1","P2"]),false);
assert.equal(pendingOrderSelection(["P1","P2"],["P1"]),true);
const blank=emptyShipment();
const fromShipping=bridgeDestination(blank,{...blank,paisDestino:"Brasil"});assert.equal(fromShipping.packing.paisDestino,"Brasil");
const fromDocument=bridgeDestination(blank,{...blank,packing:{...blank.packing,paisDestino:"Chile"}});assert.equal(fromDocument.paisDestino,"Chile");
const matched={...blank,paisDestino:"Brasil",packing:{...blank.packing,paisDestino:"Brasil"}};
assert.equal(bridgeDestination(matched,{...matched,paisDestino:"Chile"}).packing.paisDestino,"Chile");
const divergent={...matched,packing:{...matched.packing,paisDestino:"Portugal"}};
assert.equal(bridgeDestination(divergent,{...divergent,paisDestino:"Chile"}).packing.paisDestino,"Portugal");
assert.equal(bridgeDestination(divergent,{...divergent,packing:{...divergent.packing,paisDestino:"Peru"}}).paisDestino,"Brasil");
console.log("OK fluxo: campos revisados preservados, substituição explícita, seleção pendente e destino reaproveitado sem apagar divergências manuais.");
