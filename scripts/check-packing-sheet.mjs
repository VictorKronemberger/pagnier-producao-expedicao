import assert from "node:assert/strict";
import {emptyShipment,newBox,newItem,normalizeShipment} from "../lib/shipping.mjs";
import {applySheetQuantities,sheetItems} from "../lib/packing-sheet.mjs";
import {startSmallBox,finishSmallBox,placeSmallBox} from "../lib/assembly-flow.mjs";
import {finishOuterBox} from "../lib/ready-boxes.mjs";
import {packingBalance} from "../lib/packing-assistant.mjs";
import {boxReviewKey} from "../lib/box-review.mjs";
const ops=[
 {id:"op-a",nome:"OP-A",sku:"SKU-A",produto:"Produto A 50g",unidade:"UNID",quantidade:"10"},
 {id:"op-b",nome:"OP-B",sku:"SKU-B",produto:"Produto A 50g",unidade:"UNID",quantidade:"20"},
 {id:"op-kg",nome:"OP-KG",sku:"SKU-KG",produto:"Produto a granel",unidade:"KG",quantidade:"2,500"}
];
let counter=0;
const ids=()=>"item-"+(++counter),change=(boxId,opId,quantity)=>({boxId,opId,quantity});
let s={...emptyShipment(),organizacao:"direct",caixas:[{...newBox([],"box-a"),montada:false},{...newBox([newBox([],"box-a")],"box-b"),montada:false}]};
const update=(value,changes)=>applySheetQuantities(value,ops,changes,ids);
s=update(s,[change("box-a","op-a","6"),change("box-b","op-a","4"),change("box-a","op-b","2")]);
assert.equal(s.caixas[0].itens[0].sku,"SKU-A");
assert.equal(s.caixas[0].itens[0].lote,"OP-A");
assert.equal(s.caixas[0].itens[0].unidadesEmbaladas,"6");
assert.equal(s.caixas[0].itens[0].pesoUnitarioKg,"0,050");
assert.equal(s.caixas[0].itens[1].sku,"SKU-B","same product name, different OP/SKU");
assert.equal(packingBalance(s,ops)[0].remaining,"0");
const before=JSON.stringify(s);
assert.throws(()=>update(s,[change("box-a","op-a","7")]),/excede/);
assert.equal(JSON.stringify(s),before,"failed edits never mutate the source");
s=update(s,[change("box-a","op-a","9"),change("box-b","op-a","1")]);
assert.equal(s.caixas[0].itens[0].quantidade,"9","multi-column redistribution validated after whole paste");
const key=boxReviewKey(s,ops);
s.caixas[0].itens[0]={...s.caixas[0].itens[0],lote:"CUSTOM",validade:"2027-01-01",origemLote:"manual",origemValidade:"manual",hsCode:"1234",pesoUnitarioKg:"0,060",origemPeso:"manual"};
s.caixas[0].pesoBrutoKg="1";s.caixas[0].taraKg="0,1";
const originalId=s.caixas[0].itens[0].id;
s=update(s,[change("box-a","op-a","8")]);
assert.equal(s.caixas[0].itens[0].id,originalId);
assert.equal(s.caixas[0].itens[0].lote,"CUSTOM");
assert.equal(s.caixas[0].itens[0].hsCode,"1234");
assert.equal(s.caixas[0].itens[0].pesoUnitarioKg,"0,060");
assert.equal(s.caixas[0].pesoBrutoKg,"");
assert.equal(s.caixas[0].taraKg,"");
assert.notEqual(boxReviewKey(s,ops),key);
s=update(s,[change("box-a","op-kg","1,250"),change("box-b","op-kg","1.250")]);
assert.equal(packingBalance(s,ops)[2].remaining,"0");
for(const raw of ["-1","1,0001","texto","1e2","1,"])assert.throws(()=>update(s,[change("box-a","op-kg",raw)]),/três casas/);
s=update(s,[change("box-a","op-a",""),change("box-b","op-a","0")]);
assert.equal(packingBalance(s,ops)[0].remaining,"10");
assert.equal(s.caixas[0].itens.some(i=>i.opId==="op-a"),false);
assert.throws(()=>update(s,[change("box-a","foreign","1")]),/pertence/);
const duplicates={...s,caixas:s.caixas.map((b,i)=>i?b:{...b,itens:[...b.itens,{...b.itens[0],id:"other-lot",lote:"OTHER"}]})};
assert.throws(()=>update(duplicates,[change("box-a","op-b","3")]),/mais de um lote/);
let inner=startSmallBox({...s,organizacao:"mixed"},"bag-a","bag");
inner=update(inner,[change("bag-a","op-a","5")]);
assert.equal(inner.caixasEmMontagem[0].itens[0].caixaInternaId,"bag-a");
assert.throws(()=>update(inner,[change("box-a","op-a","6")]),/excede/);
inner=finishSmallBox(inner,"bag-a",ops);
assert.throws(()=>update(inner,[change("bag-a","op-a","4")]),/volte à montagem/);
inner=placeSmallBox(inner,"bag-a","box-a",ops);
inner=update(inner,[change("box-a","op-a","2")]);
assert.equal(sheetItems(inner.caixas[0],"op-a").length,1);
assert.equal(inner.caixas[0].itens.filter(i=>i.opId==="op-a").length,2,"inner contents stay distinct from direct entries");
assert.equal(inner.caixas[0].itens.find(i=>i.caixaInternaId==="bag-a").quantidade,"5");
inner=finishOuterBox(inner,"box-a",ops);
assert.throws(()=>update(inner,[change("box-a","op-a","1")]),/volte à montagem/);
assert.equal(normalizeShipment(JSON.parse(JSON.stringify(inner)),ops).caixas[0].montada,true);
const blocked={...s,organizacao:"bags"};
assert.throws(()=>update(blocked,[change("box-a","op-a","1")]),/Distribua/);
const full={...s,caixas:[{...s.caixas[0],itens:Array.from({length:100},(_,i)=>({...newItem("full-"+i),opId:"op-b",produto:ops[1].produto,unidade:"UNID",quantidade:"0"}))}]};
assert.throws(()=>update(full,[change("box-a","op-a","1")]),/100 itens/);
console.log("OK packing sheet: atomic paste, order capacity across all boxes, decimal units, metadata preservation, clearing, duplicate lots, bags, ready locks, review/weight invalidation and persistence.");