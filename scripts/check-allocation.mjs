import assert from "node:assert/strict";
import {fixture} from "./packing-fixture.mjs";
import {analyzeShipment,newBox,newItem} from "../lib/shipping.mjs";
import {updatePackingItem,productFieldsForOP} from "../lib/packing-reuse.mjs";
const {ops,shipment}=fixture();
let a=analyzeShipment(shipment,ops).allocation[0];assert.equal(a.status,"complete");assert.equal(a.caixas[0].codigo,"CX-001");assert.equal(a.caixas[0].quantidade,10);
shipment.caixas[0].itens[0].quantidade="4";a=analyzeShipment(shipment,ops).allocation[0];assert.equal(a.status,"partial");assert.equal(a.restante,6);
shipment.caixas.push({...newBox(shipment.caixas,"b2"),itens:[{...shipment.caixas[0].itens[0],id:"i2",quantidade:"6"}]});a=analyzeShipment(shipment,ops).allocation[0];assert.equal(a.status,"complete");assert.equal(a.caixas.length,2);
shipment.caixas[1].itens[0].quantidade="7";assert.equal(analyzeShipment(shipment,ops).allocation[0].status,"excess");
shipment.caixas.pop();shipment.caixas[0].itens=[];assert.equal(analyzeShipment(shipment,ops).allocation[0].status,"none");
const unit={...newItem("x"),unidade:"UN",quantidade:"",unidadesEmbaladas:""};
assert.equal(updatePackingItem(unit,{quantidade:"10"}).unidadesEmbaladas,"10");
assert.equal(updatePackingItem(unit,{unidadesEmbaladas:"7"}).quantidade,"7");
const kg={...unit,unidade:"KG",pesoUnitarioKg:"0,5"};
assert.equal(updatePackingItem(kg,{unidadesEmbaladas:"4"}).quantidade,"2");
assert.equal(updatePackingItem(kg,{quantidade:"1,5"}).unidadesEmbaladas,"3");
assert.equal(updatePackingItem({...kg,unidade:"L"},{unidadesEmbaladas:"4"}).quantidade,"");
assert.equal(updatePackingItem({...kg,unidade:"L",conteudoPorEmbalagem:"0,25"},{unidadesEmbaladas:"4"}).quantidade,"1");
assert.equal(productFieldsForOP(shipment,ops[0],"x").descricaoDocumento,ops[0].produto);
console.log("OK: alocação por caixa, parcial/completa/excesso/remoção, reaproveitamento e conversão sem presumir densidade.");
