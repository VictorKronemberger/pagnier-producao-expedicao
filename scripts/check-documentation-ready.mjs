import assert from "node:assert/strict";
import {documentationReady} from "../lib/documentation-ready.mjs";
import {confirmBoxReview} from "../lib/box-review.mjs";
import {fixture} from "./packing-fixture.mjs";
const {ops,shipment}=fixture();
const groups=[{id:"PV1",codigo:"PV 1",cliente:"Cliente teste",ordens:ops}];
const board={details:{PV1:{envio:shipment}}};
assert.deepEqual(documentationReady(board,groups),[],"unreviewed boxes stay out");
board.details.PV1.envio=confirmBoxReview(shipment,ops,"Conferente","2026-10-16T12:00:00.000Z");
const confirmed=structuredClone(board.details.PV1.envio);
board.details.PV1.envio.packing={};
assert.equal(documentationReady(board,groups).length,1,"physical readiness does not require document fields");
board.details.PV1.envio.packingExcluido=true;
assert.equal(documentationReady(board,groups).length,1,"deleted draft may be recreated with checked boxes");
board.details.PV1.envio.caixas[0].pesoBrutoKg="12";
assert.equal(documentationReady(board,groups).length,0,"physical change invalidates handoff");
board.details.PV1.envio=structuredClone(confirmed);
assert.equal(documentationReady(board,[{...groups[0],ordens:[{...ops[0],quantidade:"11"}]}]).length,0,"source changes invalidate handoff");
board.details.PV1.envio.dataEnvio="2026-10-16";
assert.equal(documentationReady(board,groups).length,0,"dispatched shipments stay out");
board.details.PV1.envio=structuredClone(confirmed);board.details.PV1.situacao="Atendido totalmente e enviado";
assert.equal(documentationReady(board,groups).length,0,"sent orders stay out");
delete board.details.PV1.situacao;
const other={...groups[0],id:"PV2",codigo:"PV 2",ordens:[{...ops[0],id:"OP2"}]};
board.details.PV1.envio.agrupamento={pedidos:["PV1","PV2"],titularKey:"a".repeat(64),titularNome:"Cliente",confirmadoEm:"2026-10-16T12:00:00.000Z"};
board.details.PV1.envio=confirmBoxReview(board.details.PV1.envio,[...ops,...other.ordens],"Conferente","2026-10-16T12:00:00.000Z");
const grouped=documentationReady(board,[...groups,other]);
assert.equal(grouped.length,1,"one queue entry per shipment");assert.equal(grouped[0].orders.length,2,"both invoice orders retained");
assert.equal(documentationReady(board,groups).length,0,"missing grouped orders cannot appear ready");
board.details.PV2={situacao:"Atendido totalmente e enviado"};
assert.equal(documentationReady(board,[...groups,other]).length,0,"sent linked order excludes shared shipment");
console.log("OK documentation readiness: checked boxes, document-independent, invalidation, dispatch and grouping.");
