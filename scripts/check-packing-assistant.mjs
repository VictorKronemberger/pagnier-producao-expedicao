import assert from "node:assert/strict";
import {emptyShipment,newBox,newItem,normalizeShipment} from "../lib/shipping.mjs";
import {normalizeBoxModels,boxFromModel} from "../lib/box-models.mjs";
import {packingBalance,suggestPackingQuantity} from "../lib/packing-assistant.mjs";
import {updatePackingItem} from "../lib/packing-reuse.mjs";
import {inspectBoxReview,confirmBoxReview} from "../lib/box-review.mjs";
import {canonical} from "../lib/autosave.mjs";
const model={id:"model1",nome:"Caixa teste",comprimentoCm:"40",larguraCm:"30",alturaCm:"20",pesoMaximoKg:"1",taraKg:"0,100"};
assert.deepEqual(normalizeBoxModels([model]),[model]);
for(const patch of [{nome:""},{larguraCm:"0"},{taraKg:""},{taraKg:"1"},{pesoMaximoKg:"0"},{alturaCm:"1e2"},{alturaCm:"9999999999999"}])assert.throws(()=>normalizeBoxModels([{...model,...patch}]));
assert.throws(()=>normalizeBoxModels([model,{...model,id:"m2"}]));
const op={id:"OP1",nome:"OP1",produto:"Produto 10g",unidade:"UN",quantidade:"100"},ops=[op];
const item={...newItem("i1"),opId:op.id,produto:op.produto,unidade:op.unidade,pesoUnitarioKg:"0,010"};
let shipment={...emptyShipment(),caixas:[{...boxFromModel([],"b1",model),itens:[item]}]};
const suggest=()=>suggestPackingQuantity(shipment,ops,"b1","i1");
assert.equal(suggest().quantity,"90");assert.equal(suggest().limited,true);
shipment.caixas[0].itens[0]=updatePackingItem(item,{quantidade:suggest().quantity});
assert.equal(suggest().quantity,"90","reapplying replaces the line; it never adds twice");
assert.equal(packingBalance(shipment,ops)[0].remaining,"10");
shipment.caixas.push({...newBox(shipment.caixas,"b2"),itens:[updatePackingItem({...item,id:"i2"},{quantidade:"5"})]});
shipment.caixas[0].pesoMaximoKg="";
assert.equal(suggest().quantity,"95","all other boxes deducted");
assert.equal(packingBalance(shipment,[op,op]).length,1,"shared OP counted once");
shipment.caixas[0].pesoMaximoKg="1";shipment.caixas[0].itens.push(updatePackingItem({...item,id:"i3"},{quantidade:"20"}));
assert.equal(suggest().quantity,"70","other lines in same box consume capacity and balance");
shipment.caixas[0].itens[1].pesoUnitarioKg="";assert.equal(suggest().quantity,"");
shipment.caixas[0].itens.pop();shipment.caixas[0].pesoBrutoKg="1,2";assert.equal(suggest().quantity,"70","measured gross reserves extra packaging");
shipment.caixas[0].pesoBrutoKg="";shipment.caixas[0].taraKg="";assert.equal(suggest().quantity,"");
shipment.caixas[0].taraKg="0,100";
const normalized=normalizeShipment(shipment,ops);assert.equal(normalized.caixas[0].pesoMaximoKg,"1");assert.equal(normalized.caixas[0].modeloNome,"Caixa teste");
const b=boxFromModel([],"b3",model);model.pesoMaximoKg="2";assert.equal(b.pesoMaximoKg,"1","model edits do not change existing boxes");
const kg={...op,unidade:"KG",quantidade:"0,955"};shipment={...emptyShipment(),caixas:[{...b,itens:[{...item,unidade:"KG"}]}]};
assert.equal(suggestPackingQuantity(shipment,[kg],"b3","i1").quantity,"0,9");
shipment.caixas[0].pesoMaximoKg="";assert.equal(suggestPackingQuantity(shipment,[kg],"b3","i1").quantity,"0,95","only whole packs suggested");
shipment.caixas[0].itens[0].unidade="L";assert.equal(suggestPackingQuantity(shipment,[{...kg,unidade:"L"}],"b3","i1").quantity,"");
shipment={...emptyShipment(),caixas:[{...b,pesoBrutoKg:"1",itens:[updatePackingItem(item,{quantidade:"90"})]}]};
assert.equal(inspectBoxReview(shipment,ops).issues.length,0);
const confirmed=confirmBoxReview(shipment,ops,"Pedro","2026-10-14T12:00:00.000Z");assert(inspectBoxReview(confirmed,ops).reviewed);
confirmed.caixas[0].pesoMaximoKg="0,9";assert.equal(inspectBoxReview(confirmed,ops).reviewed,false);assert(inspectBoxReview(confirmed,ops).issues.some(t=>t.includes("limite de peso excedido")));
const board={sequence:[],details:{}};assert.notEqual(canonical(board),canonical({...board,boxModels:[model]}));
console.log("OK assistente: saldo por OP sem duplicação, sugestões idempotentes, KG e embalagens inteiras, tara, limite, peso desconhecido, pesagem real, cópia dos modelos e revisão invalidada.");
