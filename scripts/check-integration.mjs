import assert from "node:assert/strict";
const base="http://127.0.0.1:5173";
const login=await fetch(base+"/signin-with-chatgpt?return_to=/",{redirect:"manual"});
const cookie=login.headers.get("set-cookie")?.split(";")[0];
const auth={cookie,Origin:base,"Content-Type":"application/json"};
assert.equal((await fetch(base+"/api/board")).status,401);
const response=await fetch(base+"/api/board",{headers:auth});
assert.equal(response.status,200);const first=await response.json();
assert.equal(first.snapshot.grupos.length,10);
const id=first.snapshot.grupos[0].id;
const board={sequence:[id],details:{[id]:{responsavel:"Teste local",situacao:"Programado",nota:"Verificação de persistência"}}};
const write=await fetch(base+"/api/board",{method:"PUT",headers:auth,body:JSON.stringify({board,revision:first.revision})});
assert.equal(write.status,200);const written=await write.json();
const after=await (await fetch(base+"/api/board",{headers:auth})).json();
assert.deepEqual(after.board,board);assert.equal(after.revision,written.revision);
const stale=await fetch(base+"/api/board",{method:"PUT",headers:auth,body:JSON.stringify({board,revision:first.revision})});
assert.equal(stale.status,409);
const invalid=await fetch(base+"/api/board",{method:"PUT",headers:auth,body:JSON.stringify({board:{sequence:["fake-id"],details:{}},revision:after.revision})});
assert.equal(invalid.status,400);
const external=await fetch(base+"/api/board",{method:"PUT",headers:{...auth,Origin:"https://outside.invalid"},body:JSON.stringify({board,revision:after.revision})});
assert.equal(external.status,403);
const restore=await fetch(base+"/api/board",{method:"PUT",headers:auth,body:JSON.stringify({board:first.board,revision:after.revision})});
assert.equal(restore.status,200);
const page=await fetch(base,{headers:auth});assert.equal(page.status,200);assert((await page.text()).includes("Cada pedido"));
